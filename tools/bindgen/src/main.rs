// Generates src/Quiche.NET/Native/NativeMethods.g.cs from quiche's Rust FFI.
// Usage: cargo run -- <quiche-checkout-dir> <output-cs-path>
// The quiche checkout is NOT in this repo; point at any checkout of the
// pinned version (see native/QUICHE_VERSION), e.g. a clone at that tag.
use std::env;
use std::path::PathBuf;

fn main() {
    let args: Vec<String> = env::args().collect();
    if args.len() != 3 {
        eprintln!("usage: quiche-bindgen <quiche-dir> <output.cs>");
        std::process::exit(2);
    }
    let quiche_dir = PathBuf::from(&args[1]);
    let ffi_rs = quiche_dir.join("quiche/src/ffi.rs");
    let out = PathBuf::from(&args[2]);

    // NB: input_EXTERN_file, not input_bindgen_file. Bindgen files yield
    // `extern "C" { ... }` foreign declarations (here: only inet_ntop);
    // quiche's API is `#[no_mangle] pub extern "C" fn` definitions,
    // which only the extern collector picks up.
    csbindgen::Builder::default()
        .input_extern_file(&ffi_rs)
        // ffi.rs defines quiche_conn_new_with_tls_and_client_dcid TWICE
        // (cfg-gated: with and without the custom-client-dcid feature).
        // Our builds enable only `ffi`, and the managed API never needs
        // custom client DCIDs, so drop it rather than emit a duplicate
        // C# method that cannot compile. Keep the default underscore
        // exclusion alongside it.
        .method_filter(|x| {
            !x.starts_with('_') &&
                x != "quiche_conn_new_with_tls_and_client_dcid"
        })
        // A few signatures spell size_t/ssize_t where the rest use
        // libc::size_t (which csbindgen already maps to nuint/nint).
        // Normalize the stragglers so the output compiles without
        // hand-written aliases.
        .csharp_type_rename(|x| {
            if x == "size_t" {
                "nuint".to_string()
            } else if x == "ssize_t" {
                "nint".to_string()
            } else {
                x
            }
        })
        .csharp_namespace("Quiche.Native")
        .csharp_class_name("NativeMethods")
        .csharp_class_accessibility("internal")
        .csharp_dll_name("quiche")
        .csharp_file_header(
            "// <auto-generated />\n// Generated from quiche's C FFI (quiche/src/ffi.rs) with csbindgen.\n// Do not edit by hand: re-run tools/bindgen (see tools/bindgen/README.md)\n// on a checkout of the pinned quiche version in native/QUICHE_VERSION.\n",
        )
        .generate_csharp_file(&out)
        .unwrap();
    println!("wrote {}", out.display());
}
